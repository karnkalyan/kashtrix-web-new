/**
 * Resolves page metadata by checking the PageMeta table in the database first.
 * If the user has customized the metadata in the admin panel, the custom version is returned.
 * Otherwise, falls back to the static defaults.
 */
export async function getPageMetadata(
  pathname: string,
  fallback?: Partial<PageMetaItem>
): Promise<Metadata> {
  const normalizedPath = pathname.startsWith("/") ? pathname : `/${pathname}`;
  const defaultItem =
    DEFAULT_PAGE_CATALOG.find((p) => p.path === normalizedPath) ||
    (fallback as PageMetaItem | undefined);

  let custom: any = null;
  try {
    custom = await prisma.pageMeta.findUnique({
      where: { path: normalizedPath },
    });
  } catch (error) {
    // Database query failed or table not ready, safely fall back
  }

  const title = custom?.title || defaultItem?.title || "Kashtrix — Broadcast & Telecom Software";
  const description =
    custom?.description ||
    defaultItem?.description ||
    "Kashtrix enterprise software for television broadcasting, master control playout, and telecom OSS/BSS.";
  const rawKeywords = custom?.keywords || defaultItem?.keywords || "";
  const keywords = Array.isArray(rawKeywords)
    ? rawKeywords
    : rawKeywords.split(",").map((k: string) => k.trim()).filter(Boolean);
  const canonical = custom?.canonical || defaultItem?.canonical || `https://kashtrix.com${normalizedPath}`;
  const ogTitle = custom?.ogTitle || title;
  const ogDesc = custom?.ogDesc || description;
  const ogImage = custom?.ogImage || defaultItem?.ogImage || "/og.svg";
  const noIndex = custom?.noIndex ?? defaultItem?.noIndex ?? false;

  return {
    title,
    description,
    keywords,
    alternates: {
      canonical,
    },
    openGraph: {
      title: ogTitle,
      description: ogDesc,
      url: canonical,
      siteName: "Kashtrix",
      images: [
        {
          url: ogImage,
          width: 1200,
          height: 630,
          alt: title,
        },
      ],
      locale: "en_US",
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title: ogTitle,
      description: ogDesc,
      images: [ogImage],
    },
    robots: noIndex
      ? { index: false, follow: false }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-video-preview": -1,
            "max-image-preview": "large",
            "max-snippet": -1,
          },
        },
  };
}
